const $ = (s) => document.querySelector(s);
let uiLang = "en";
let currentTool = "prompt";
let latestResults = [];

function t(key){return (translations[uiLang] && translations[uiLang][key]) || translations.en[key] || key;}
function safeText(value){return String(value).replace(/[&<>"']/g, c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));}
function applyLanguage(){
  document.documentElement.lang = uiLang === "hi" ? "hi" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const value=t(el.dataset.i18n);
    if(value) el.innerHTML=value;
  });
  $("#languageToggle").textContent = uiLang === "en" ? "हिंदी" : "English";
  $("#toolHeading").textContent=t("heading")[currentTool];
  const cat=$("#category");
  [...cat.options].forEach(o=>{if(t("categories")[o.value])o.textContent=t("categories")[o.value];});
  const style=$("#style");
  [...style.options].forEach(o=>{if(t("styles")[o.value])o.textContent=t("styles")[o.value];});
}
function setTool(tool){
  currentTool=tool;
  document.querySelectorAll(".tool-tab").forEach(b=>b.classList.toggle("active",b.dataset.tool===tool));
  $("#toolHeading").textContent=t("heading")[tool];
  $("#resultArea").hidden=true;
  $("#generatorForm").scrollIntoView({behavior:"smooth",block:"nearest"});
}
function buildResults(topic, category, duration, style, outputLang){
  const d=translations[outputLang==="hi"?"hi":"en"];
  const cleanTopic=topic.trim();
  const styleName=d.styles[style]||style;
  const catName=d.categories[category]||category;
  const titleList=d.titlePatterns.map(s=>s.replaceAll("{topic}",cleanTopic).replaceAll("{duration}",duration));
  const description=d.descIntro.replaceAll("{topic}",cleanTopic);
  const tags=[...new Set([...(d.categoryTags[category]||d.categoryTags.other),...d.genericTags, "#"+cleanTopic.split(/\s+/).filter(Boolean).slice(0,3).join("").replace(/[^a-zA-Z0-9]/g,"")])].filter(x=>x.length>1).join(" ");
  const thumbs=d.thumbPatterns.map(s=>s.replaceAll("{topic}",cleanTopic));
  const scenes=(category==="food"?d.foodScenes:d.generalScenes);
  const prompt=[
    d.promptIntro+" "+cleanTopic+".",
    `${d.promptStyle}: ${styleName}.`,
    `${d.promptDuration}: ${duration} ${d.seconds}.`,
    `${d.scenes}:`,
    ...scenes.map((s,i)=>`${i+1}. ${s}`),
    d.voiceLine,
    d.promptReq,
    `Category: ${catName}. Output should be suitable for a general audience.`
  ].join("\n");
  if(currentTool==="prompt") return [{title:d.output+" — "+d.heading.prompt,text:prompt}];
  if(currentTool==="title") return [
    {title:d.title,text:titleList.map((s,i)=>`${i+1}. ${s}`).join("\n")},
    {title:d.description,text:description}
  ];
  if(currentTool==="hashtags") return [
    {title:d.tags,text:tags},
    {title:uiLang==="hi"?"Hashtag tip":"Hashtag tip",text:uiLang==="hi"?"Sirf wahi hashtags rakhein jo video se sach mein related hon.":"Keep only hashtags that are genuinely relevant to your video."}
  ];
  return [{title:d.thumbnail,text:thumbs.map((s,i)=>`${i+1}. ${s}`).join("\n")}];
}
function showResults(results){
  latestResults=results;
  $("#resultContent").innerHTML="";
  results.forEach((item,index)=>{
    const card=document.createElement("article");
    card.className="result-card";
    const h=document.createElement("h4");h.textContent=item.title;
    const p=document.createElement("p");p.textContent=item.text;
    const b=document.createElement("button");b.type="button";b.className="btn btn-ghost card-copy";b.textContent=t("copy");
    b.addEventListener("click",()=>copyText(item.text));
    card.append(h,p,b);$("#resultContent").append(card);
  });
  $("#resultArea").hidden=false;
}
function showToast(message){
  const el=$("#toast");el.textContent=message;el.classList.add("show");
  window.clearTimeout(showToast.timer);showToast.timer=window.setTimeout(()=>el.classList.remove("show"),2200);
}
async function copyText(text){
  try{
    if(navigator.clipboard && window.isSecureContext){await navigator.clipboard.writeText(text);}
    else{
      const ta=document.createElement("textarea");ta.value=text;ta.style.position="fixed";ta.style.opacity="0";document.body.appendChild(ta);ta.select();
      const ok=document.execCommand("copy");ta.remove();if(!ok)throw new Error("copy failed");
    }
    showToast(t("copied"));
  }catch(e){showToast(t("copyFail"));}
}
